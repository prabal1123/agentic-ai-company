import json

from .base import BaseAgent


class BackendDeveloperAgent(BaseAgent):
    name = "backend_developer"

    def __init__(self, llm, filesystem, terminal, test_runner):
        super().__init__(llm)

        self.filesystem = filesystem
        self.terminal = terminal
        self.test_runner = test_runner

    def run(self, product, requirements, architecture):
        prompt = f"""
You are a senior backend software engineer working inside an
AI-native software company.

Your job is to create the backend implementation for the following
software.

PRODUCT:
{product}

REQUIREMENTS:
{requirements}

ARCHITECTURE:
{architecture}

Return ONLY valid JSON.

The JSON must have this structure:

{{
    "summary": "short implementation summary",
    "files": [
        {{
            "path": "relative/path/to/file.py",
            "content": "complete file contents"
        }}
    ]
}}

Rules:

1. Paths must be relative paths.
2. Never use absolute paths.
3. Do not use ../ in paths.
4. Provide complete file contents.
5. Create only files necessary for the backend.
6. IMPLEMENTATION LANGUAGE CONSTRAINT (overrides anything in the
   ARCHITECTURE section above): this code runs as standalone Python
   scripts in an isolated workspace with NO web framework runtime
   configured. Even if the architecture recommends Django, Django
   REST Framework, Flask, SQLAlchemy, or any other framework, you
   MUST implement models, business logic, and API handlers as plain
   Python classes or dataclasses with NO framework base classes and
   NO framework imports (no `django.db.models.Model`,
   `serializers.ModelSerializer`, `flask.*`, etc.). Persistence can
   be simulated with plain Python data structures (e.g. dicts/lists
   held in memory or passed explicitly) rather than a real database
   connection.
7. Follow the functional requirements and business logic described
   in the architecture and requirements, but always through the
   plain-Python implementation constraint in rule 6.
8. Include a tests.py file using pytest-style test functions.
9. Do not include markdown.
10. Do not include explanations outside the JSON.
"""

        response = self.llm.generate(prompt)

        return self._parse_response(response)

    def _parse_response(self, response):
        """
        Convert the LLM response into a Python dictionary.
        """

        response = response.strip()

        # Remove markdown fences if the model ignores the instruction.
        if response.startswith("```"):
            lines = response.splitlines()

            if lines[0].startswith("```"):
                lines = lines[1:]

            if lines and lines[-1].strip() == "```":
                lines = lines[:-1]

            response = "\n".join(lines).strip()

        try:
            data = json.loads(response)
        except json.JSONDecodeError as exc:
            raise ValueError(
                f"Backend Agent returned invalid JSON: {exc}"
            )

        if "files" not in data:
            raise ValueError(
                "Backend Agent response does not contain 'files'."
            )

        return data

    def execute(self, implementation):
        """
        Create the files generated by the Backend Agent.
        Returns the list of file paths written, for reuse by test()/compile checks.
        """

        results = []

        for file_data in implementation["files"]:
            path = file_data["path"]
            content = file_data["content"]

            result = self.filesystem.create_file(
                path,
                content,
            )

            results.append(result)

        return results

    def test(self, implementation):
        """
        Compile-check every generated .py file, then run pytest.
        Uses the actual file list from the implementation instead of a
        hardcoded guess.
        """

        py_files = [
            f["path"] for f in implementation["files"]
            if f["path"].endswith(".py")
        ]

        compile_result = self.test_runner.compile_python(py_files)

        if not compile_result["success"]:
            return {
                "stage": "compile",
                **compile_result,
            }

        test_result = self.test_runner.run_pytest()

        return {
            "stage": "pytest",
            **test_result,
        }
    